import 'dotenv/config';
import express from 'express';
import cookieParser from 'cookie-parser';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import authRoutes from '../src/routes/auth.js';
import matchRoutes from '../src/routes/matches.js';
import extraRoutes from '../src/routes/extra-routes.js';
const app=express();
app.disable('x-powered-by');app.use(express.json({limit:'32kb'}));app.use(cookieParser());
app.get('/api/health',(_req,res)=>res.json({status:'ok',service:'ChessNest'}));
app.use('/api/auth',authRoutes);app.use('/api/matches',matchRoutes);app.use('/api',extraRoutes);
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../public');app.use(express.static(root));app.get('/',(_req,res)=>res.sendFile(path.join(root,'index.html')));
app.use((err,req,res,next)=>{console.error(err);res.status(500).json({error:'Internal server error.'});});
const port=Number(process.env.PORT||3000);app.listen(port,()=>console.log(`ChessNest at http://localhost:${port}`));
